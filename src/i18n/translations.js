/* Page-level and core additions for the wider language set. Newly added
   languages start empty so coverage() reports real numbers and t() falls
   back to English per key instead of pretending to be complete. */
/* Merge per language across every source file: a later file must add to
   a language, never replace the earlier ones. */
[LOCALES_A, LOCALES_B, LOCALES_C, LOCALES_CORE, LOCALES_D, LOCALES_E, LOCALES_F].forEach((source) => {
  Object.keys(source).forEach((code) => {
    if (!SUPPORTED.has(code)) return;
    if (!TRANSLATIONS[code]) TRANSLATIONS[code] = {};
    Object.assign(TRANSLATIONS[code], source[code]);
  });
});

export function coverage() {
  const total = Object.keys(TRANSLATIONS.en).length;
  const out = {};
  Object.keys(TRANSLATIONS).forEach((code) => {
    const translated = Object.keys(TRANSLATIONS.en).filter(
      (k) => TRANSLATIONS[code][k] && String(TRANSLATIONS[code][k]).trim()
    ).length;
    out[code] = Math.round((translated / total) * 100);
  });
  return out;
}
